#!/usr/bin/env python3
"""Replace the inlined tables in paper.tex with freshly generated ones.

The four tables used to be \\input from separate files, which kept them in
step with the data automatically.  They are now written out in paper.tex so
that the manuscript is a single file to hand around, and the generators would
otherwise write to files nothing reads.  This regenerates each table and
splices it back into paper.tex between its marker comment and the end of the
environment it opens.

    python3 scripts/sync_tables.py            # rewrite paper.tex in place
    python3 scripts/sync_tables.py --check    # report drift, change nothing

``--check`` is the one to run before a submission build: it exits non-zero if
any inlined table no longer matches what the data produces.
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.expanduser('~/code/biogas/ADM1/papers/mypaper/paper.tex')

# marker name -> (generator, environment the table opens).  Most generators
# take an output directory; export_hyperparams takes the output file.
# The environment is the one the generated fragment itself closes: two of
# them emit a bare tabular and let paper.tex supply the float and caption.
TABLES = {
    'table_results': ('build_tables.py', 'tabular'),
    'table_cmdp': ('build_tables.py', 'tabular'),
    'table_ablation': ('build_ablation_table.py', 'table*'),
    # table_hyperparams is written from probe_hyper.py, which reads the
    # effective values back from the trained models; export_hyperparams.py
    # only knows what was passed at launch, so it must not overwrite it.
}
TAKES_FILE = {'export_hyperparams.py': 'table_hyperparams.tex'}

MARKER = r'% ---- {name} ----'


def generate(outdir):
    """Run each generator once into a scratch directory."""
    for script in sorted({s for s, _ in TABLES.values()}):
        target = outdir
        if script in TAKES_FILE:
            target = os.path.join(outdir, TAKES_FILE[script])
        r = subprocess.run([sys.executable, os.path.join(HERE, script),
                            target], capture_output=True, text=True)
        if r.returncode:
            raise SystemExit(f'{script} failed:\n{r.stderr}')


def current(paper, name, env):
    """The marker line and the table body that follows it."""
    m = re.search(MARKER.format(name=name), paper)
    if not m:
        raise SystemExit(f'marker for {name} not found in paper.tex')
    end = paper.index('\\end{%s}' % env, m.end()) + len('\\end{%s}' % env)
    return m.group(0), paper[m.end():end].lstrip('\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true',
                    help='report drift without writing')
    ap.add_argument('paper', nargs='?', default=PAPER)
    a = ap.parse_args()

    paper = open(a.paper).read()
    with tempfile.TemporaryDirectory() as tmp:
        generate(tmp)
        drift = []
        for name, (_, env) in TABLES.items():
            fresh = open(os.path.join(tmp, f'{name}.tex')).read()
            fresh = re.sub(r'^% Auto-generated by [^\n]*\n', '', fresh)
            fresh = fresh.rstrip('\n')
            marker, old = current(paper, name, env)
            if old == fresh:
                print(f'  {name:<22} up to date')
                continue
            drift.append(name)
            print(f'  {name:<22} DIFFERS')
            if not a.check:
                paper = paper.replace(marker + '\n' + old,
                                      marker + '\n' + fresh)

    if a.check:
        print(f'\n{len(drift)} of {len(TABLES)} tables differ from the data')
        raise SystemExit(1 if drift else 0)

    if drift:
        open(a.paper, 'w').write(paper)
        print(f'\nrewrote {len(drift)} table(s) in {a.paper}')
    else:
        print('\nnothing to do')


if __name__ == '__main__':
    main()
